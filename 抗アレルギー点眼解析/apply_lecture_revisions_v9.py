def replace_in_frame(tf, old, new):
    """テキストフレーム内の old を new に置換（run をまたぐ場合も対応）。"""
    hit = 0
    for p in tf.paragraphs:
        runs = p.runs
        if not runs:
            continue
        full = "".join(r.text for r in runs)
        i = full.find(old)
        if i < 0:
            continue
        j = i + len(old)
        pos = 0
        for r in runs:
            s, e = pos, pos + len(r.text)
            pos = e
            if e <= i or s >= j:
                continue
            head = r.text[:max(0, i - s)]
            tail = r.text[max(0, j - s):] if e > j else ""
            r.text = head + (new if s <= i else "") + tail
        hit += 1
    return hit


def main():
    os.makedirs(BACKUP_DIR, exist_ok=True)
    bk = os.path.join(BACKUP_DIR, os.path.basename(SRC))
    if not os.path.exists(bk):
        shutil.copyfile(SRC, bk)
        print("backup -> %s" % os.path.relpath(bk, OUT))

    prs = Presentation(SRC)
    done = {}
    # --- 全体置換 ---
    for i, s in enumerate(prs.slides, 1):
        frames = []
        for sh in s.shapes:
            if sh.has_text_frame:
                frames.append(sh.text_frame)
            if getattr(sh, "has_table", False):
                for row in sh.table.rows:
                    for c in row.cells:
                        frames.append(c.text_frame)
        if s.has_notes_slide:
            frames.append(s.notes_slide.notes_text_frame)
        for old, new in GLOBAL:
            for tf in frames:
                if replace_in_frame(tf, old, new):
                    done[old] = done.get(old, 0) + 1

    print("--- 全体置換 ---")
    for old, _ in GLOBAL:
        n = done.get(old, 0)
        print("  %s  %s" % ("OK %d件" % n if n else "★0件", old[:56]))

    # --- 表セル指定置換 ---
    print("--- 表セル置換 ---")
    for i, s in enumerate(prs.slides, 1):
        if i not in CELLS:
            continue
        tbls = [sh.table for sh in s.shapes if getattr(sh, "has_table", False)]
        if not tbls:
            print("  ★slide %d: 表なし" % i)
            continue
        tb = tbls[0]
        for ri, ci, old, new in CELLS[i]:
            if ri >= len(tb.rows) or ci >= len(tb.columns):
                print("  ★slide %d [%d,%d]: 範囲外" % (i, ri, ci))
                continue
            cell = tb.cell(ri, ci)
            if cell.text.strip() != old:
                print("  ★slide %d [%d,%d]: 不一致（現値 '%s' / 期待 '%s'）"
                      % (i, ri, ci, cell.text.strip()[:26], old))
                continue
            replace_in_frame(cell.text_frame, old, new)
        print("  slide %d: %d セル処理" % (i, len(CELLS[i])))

    prs.save(SRC)
    print("-> %s" % SRC)


if __name__ == "__main__":
    main()
