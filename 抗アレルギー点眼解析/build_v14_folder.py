def bump(s):
    """ファイル名と本文中の補遺図番号をまとめて繰り上げる。"""
    s = re.sub(r"SupplFigureS([2-5])",
               lambda m: "SupplFigureS" + FIGMAP[m.group(1)], s)
    return renumber_text(s)


def build_readme():
    src = io.open(os.path.join(V13, "README.md"), encoding="utf-8").read()
    src = src.replace("投稿用ファイル 対応表（原稿 v13・投稿改定ver）",
                      "投稿用ファイル 対応表（原稿 v14・投稿改定ver）")
    src = src.replace("_v13_提出", "_v14_提出")
    src = src.replace("**Suppl Fig S1〜S5**", "**Suppl Fig S1〜S4**")
    src = src.replace(
        "- 英訳時は図中に日本語が残っていないか確認する"
        "（Suppl Fig S1〜S5 は日本語が残っている）。",
        "- 補遺図は英語版（`SupplFigureS1_en.png`〜`S4_en.png` と "
        "`SupplFigureSまとめ_v14_提出`）を投稿に用いる。日本語版の "
        "`SupplFigureS1.png`〜`S4.png` は同じ値の原図として残してある。")
    out = []
    for line in src.split("\n"):
        if line.startswith("| `SupplFigureS1.png`") or \
           line.startswith("| `SupplFigureS1.pptx`"):
            continue                                    # 模式図の行を落とす
        if line.startswith("|"):
            # 表の最終列（コピー元のパス、および v10〜v12 の変更履歴）は
            # 当時のファイル名・図番号を指すので触らない
            cells = line.split("|")
            body = "|".join(bump(c) for c in cells[:-2])
            line = "|".join([body] + cells[-2:])
        else:
            line = bump(line)
        out.append(line)
    return "\n".join(out) + V14_SECTION


