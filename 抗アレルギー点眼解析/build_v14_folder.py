def newname(f):
    m = re.match(r"SupplFigureS([2-5])(.*)$", f)
    if m:
        return "SupplFigureS%s%s" % (FIGMAP[m.group(1)], m.group(2))
    return f.replace("_v13_", "_v14_")


def renumber_text(s):
    """本文中の `Supplementary Figure S2` / `Suppl Fig S2` 等を繰り上げる。

    `Supplementary Table S…` には触らない（`Fig` を含む語にのみ一致させる）。
    """
    return re.sub(r"(Suppl(?:ementary)?\.? Fig(?:ure)? )S([2-5])",
                  lambda m: m.group(1) + "S" + FIGMAP[m.group(2)], s)


def patch_zip(path, repl):
    """zip 内の *.xml を文字列置換する。repl は (old, new, 想定件数) の並び。"""
    zin = zipfile.ZipFile(path)
    parts, counts = {}, {old: 0 for old, _, _ in repl}
    for item in zin.infolist():
        data = zin.read(item.filename)
        if item.filename.endswith(".xml"):
            x = data.decode("utf-8")
            for old, new, _ in repl:
                counts[old] += x.count(old)
                x = x.replace(old, new)
            data = x.encode("utf-8")
        parts[item.filename] = data
    infos = list(zin.infolist())
    zin.close()
    for old, _, want in repl:
        if counts[old] != want:
            raise SystemExit("%s: %r が %d 件（想定 %d 件）"
                             % (os.path.basename(path), old, counts[old], want))
    tmp = path + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in infos:
            zout.writestr(item, parts[item.filename])
    shutil.move(tmp, path)


