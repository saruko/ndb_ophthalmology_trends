    n = 0
    for anchor, old, new in EDITS:
        i = find(P, anchor)
        if old not in P[i].text:
            raise KeyError("段落は見つかったが置換元がない: %s / %s" % (anchor[:20], old[:40]))
        ed.replace(P[i], old, new)
        n += 1
    for ti, ri, ci, old, new in TABLE_EDITS:
        cell = doc.tables[ti].rows[ri].cells[ci]
        para = [p for p in cell.paragraphs if old in p.text]
        if not para:
            raise KeyError("表のセルに置換元がない: %s" % old)
        ed.replace(para[0], old, new)
        n += 1
    doc.save(DEST)
    print("-> %s （変更履歴つき、%d 箇所）" % (DEST, n))

    d2 = Document(DEST)
