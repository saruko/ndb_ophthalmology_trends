# 2. 品目名の分類
# ----------------------------------------------------------------------
def is_sentei(name: str) -> bool:
    """長期収載品の選定療養分（2024年10月〜）。先発品として扱う。"""
    return "（選）" in name or "(選)" in name


def has_maker_suffix(name: str) -> bool:
    """「メーカー名」付きの後発品銘柄か。"""
    return "「" in name


def product_type(code: str, name: str) -> str:
    """brand / generic_maker / generic_unified を返す。

    先発品名で始まる品目（「（選）」付きを含む）を先発品とする。
    それ以外のうち「メーカー名」付きをメーカー銘柄、無印を統一名収載品とする。
    """
    if any(name.startswith(p) for p in BRAND_PREFIX[code]):
        return "brand"
    return "generic_maker" if has_maker_suffix(name) else "generic_unified"


def is_generic(ptype: str) -> bool:
    return ptype.startswith("generic")


