# 4. GE比率の信頼性4分類
# ----------------------------------------------------------------------
GE_CLASS_LABEL = {
    "A": "真値0%（後発品が未収載）",
    "B": "算出不能（後発品は収載済みだが上位品目の足切りで非掲載）",
    "C": "比較不能（後発品の収載初年度・部分年のみ）",
    "D": "信頼可（足切り撤廃後）",
}

GE_CLASS_NOTE = {
    "A": "当該年度末時点で後発品が薬価収載されていない。GE比率0%は実態を反映した真値。",
    "B": "後発品は薬価収載済みだが、NDBオープンデータの上位品目制限により非掲載または一部のみ掲載。"
         "公表値から算出したGE比率は実態を反映しないため、経年比較に使用してはならない。",
    "C": "後発品の収載初年度にあたり、年度内の一部期間しか含まれない。さらに上位品目制限も"
         "残るため、二重に過小評価される。前後年度との比較は不可。",
    "D": "第9回NDBオープンデータ（2022年度）以降は上位品目の足切りが撤廃され、"
         "全品目が公開される。GE比率は経年比較に使用できる。",
}


def ge_class(code: str, year: int) -> str:
    """成分×年度に対するGE比率の信頼性区分（A/B/C/D）を返す。"""
    first, _ = GE_FIRST_LISTING[code]
    if first == "none":
        # 後発品が存在しない成分は、足切りの有無にかかわらず0%が真値。
        return "A"
    if year >= UNCAPPED_FROM_YEAR:
        return "D"
    if first is None:
        # 解析期間開始より前から後発品が流通している。
        return "B"
    if year < first:
        return "A"
    if year == first:
        return "C"
    return "B"


def ge_usable(cls: str) -> bool:
    """GE比率を数値として提示・比較してよい区分か。"""
    return cls in ("A", "D")


