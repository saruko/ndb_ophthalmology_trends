def make_clean(path):
    """変更履歴を「すべて承諾」した状態の docx を作る。

    w:del は中身ごと捨て、w:ins は殻を外して中身を残す。段落記号が削除扱いの段落
    （pPr/rPr に w:del がある）は段落ごと取り除く。これをやらないと、削除した段落が
    空段落として残る。
    """
    W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
    doc = Document(path)
    body = doc.element.body

    # 1) 段落記号が削除扱いの段落を丸ごと除去
    dropped = 0
    for para in list(body.iter("{%s}p" % W)):
        pPr = para.find("{%s}pPr" % W)
        if pPr is None:
            continue
        rPr = pPr.find("{%s}rPr" % W)
        if rPr is None or rPr.find("{%s}del" % W) is None:
            continue
        parent = para.getparent()
        if parent is not None:
            parent.remove(para)
            dropped += 1

    # 2) 残りの w:del は中身ごと捨てる
    for el in list(body.iter("{%s}del" % W)):
        parent = el.getparent()
        if parent is not None:
            parent.remove(el)

    # 3) w:ins は殻を外して中身を残す
    for el in list(body.iter("{%s}ins" % W)):
        parent = el.getparent()
        if parent is None:
            continue
        idx = list(parent).index(el)
        for k, ch in enumerate(list(el)):
            el.remove(ch)
            parent.insert(idx + k, ch)
        parent.remove(el)

    doc.save(DEST_CLEAN)
    print("-> %s  （履歴確定版、削除段落 %d を除去）" % (DEST_CLEAN, dropped))


if __name__ == "__main__":
    p = main()
    make_clean(p)
