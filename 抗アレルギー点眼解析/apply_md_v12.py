def _row(s, y):
    return G[(G.series == s) & (G.year == y)].iloc[0]


def _fl(v, nd=3):
    return f"{math.floor(v * 10 ** nd) / 10 ** nd:.{nd}f}"


def _ce(v, nd=3):
    return f"{math.ceil(v * 10 ** nd) / 10 ** nd:.{nd}f}"


def iv(s, y, m, sep="〜", box=False):
    """識別区間の表示。下限は切り捨て、上限は切り上げ（表示区間が計算区間を包含する）。"""
    r = _row(s, y)
    suf = "_boxonly" if box else ""
    return _fl(r[m + "_min" + suf]) + sep + _ce(r[m + "_max" + suf])


def br(s, y, m, box=False):
    """md で使われている [下限, 上限] 形式。"""
    r = _row(s, y)
    suf = "_boxonly" if box else ""
    return "[" + _fl(r[m + "_min" + suf]) + ", " + _ce(r[m + "_max" + suf]) + "]"


def pub(s, y, m):
    return f"{_row(s, y)[m + '_published']:.3f}"


