def apply_to(path, tracked):
    name = os.path.basename(path)
    os.makedirs(BACKUP_DIR, exist_ok=True)
    bk = os.path.join(BACKUP_DIR, name)
    if not os.path.exists(bk):
        shutil.copyfile(path, bk)
        print("  backup -> %s" % os.path.relpath(bk, OUT))

    d = docx.Document(path)
    ed = TrackedEditor(DATE) if tracked else PlainEditor()
    done = miss = 0

    for key, old, new in PARA_EDITS:
        p = para_by(d, key)
        if p is None:
            print("  ★段落なし: %s" % key[:36])
            miss += 1
            continue
        if old not in text_of(p._p):
            print("  ★旧文字列なし: %s ... %s" % (key[:24], old[:40]))
            miss += 1
            continue
        ed.replace(p, old, new)
        done += 1

    # Table 1
    t1 = next((t for t in d.tables
               if text_of(t.rows[0].cells[0]._tc).strip() == "成分"), None)
    if t1 is None:
        print("  ★Table 1 が見つからない")
    else:
        for row in t1.rows[1:]:
            label = text_of(row.cells[0]._tc).strip()
            for (lab, col), (old, new) in TABLE1_EDITS.items():
                if lab != label:
                    continue
                cell = row.cells[col]
                if old not in text_of(cell._tc):
                    print("  ★T1 %s[%d] に '%s' なし（現値 '%s'）"
                          % (lab, col, old, text_of(cell._tc).strip()))
                    miss += 1
                    continue
                ed.replace(cell.paragraphs[0], old, new)
                done += 1

    # Table 3
    t3 = next((t for t in d.tables
               if text_of(t.rows[0].cells[0]._tc).strip() == "年度"), None)
    if t3 is None:
        print("  ★Table 3 が見つからない")
    else:
        for row in t3.rows[1:]:
            year = text_of(row.cells[0]._tc).strip()
            for (yr, col), (old, new) in TABLE3_EDITS.items():
                if yr != year:
                    continue
                cell = row.cells[col]
                if old not in text_of(cell._tc):
                    print("  ★T3 %s[%d] に '%s' なし（現値 '%s'）"
                          % (yr, col, old, text_of(cell._tc).strip()))
                    miss += 1
                    continue
                ed.replace(cell.paragraphs[0], old, new)
                done += 1

    d.save(path)
    print("  %s: 適用 %d 件 / 未適用 %d 件（%s）"
          % (name, done, miss, "変更履歴あり" if tracked else "履歴なし"))
    return miss


def main():
    only = sys.argv[1] if len(sys.argv) > 1 else None
    total_miss = 0
    for name, tracked in TARGETS:
        if only and only not in name:
            continue
        fp = os.path.join(OUT, name)
        if not os.path.exists(fp):
            print("  ファイルなし: %s" % name)
            continue
        print("=" * 70)
        total_miss += apply_to(fp, tracked)
    print("=" * 70)
    print("未適用の合計: %d 件" % total_miss)


if __name__ == "__main__":
    main()
