def text_of(el):
    return "".join(n.text or "" for n in el.iter(qn("w:t")))


def para_by(doc, needle):
    for p in doc.paragraphs:
        if needle in text_of(p._p):
            return p
    return None


# ----------------------------------------------------------------------
# 履歴を残さない直接置換（マークなし版用）
# ----------------------------------------------------------------------
def plain_replace(par, old, new):
    """段落内の old を new に置換する。run をまたぐ場合も扱う。"""
    runs = par.runs
    if not runs:
        return False
    full = "".join(r.text for r in runs)
    i = full.find(old)
    if i < 0:
        return False
    j = i + len(old)
    pos = 0
    for r in runs:
        s, e = pos, pos + len(r.text)
        pos = e
        if e <= i or s >= j:
            continue
        head = r.text[:max(0, i - s)]
        tail = r.text[max(0, j - s):] if e > j else ""
        r.text = head + (new if s <= i else "") + tail
    return True


class PlainEditor:
    def replace(self, par, old, new):
        return plain_replace(par, old, new)


